const WRITABLE = ['type', 'title', 'description', 'subject', 'link', 'tags'];

const readBody = (body) => {
  const updates = {};

  for (const field of WRITABLE) {
    if (!(field in body)) continue;
    const value = body[field];

    if (field === 'type') {
      if (!TYPES.includes(value)) {
        throw new ApiError(400, `type must be one of: ${TYPES.join(', ')}`);
      }
      updates.type = value;
    } else if (field === 'tags') {
      // Multipart sends this as a comma-separated string; JSON sends an array.
      const list = Array.isArray(value)
        ? value
        : typeof value === 'string'
          ? value.split(',')
          : [];
      updates.tags = normalizeTags(list, 15) ?? [];
    } else {
      updates[field] = typeof value === 'string' ? value.trim() : '';
    }
  }

  return updates;
};

/**
 * POST /api/resources
 *
 * Accepts either multipart (with a file) or plain JSON (link only) — multer
 * ignores anything that isn't multipart, so one handler covers both.
 */
const createResource = asyncHandler(async (req, res) => {
  const updates = readBody(req.body);

  if (!updates.type) throw new ApiError(400, 'Pick a category');

  const file = req.file
    ? {
        storedName: req.file.filename,
        originalName: req.file.originalname,
        sizeBytes: req.file.size,
        mimeType: req.file.mimetype,
      }
    : null;

  // A resource nobody can open is just a title. One of the two is required.
  if (!file && !updates.link) {
    unlinkQuietly(file?.storedName);
    throw new ApiError(400, 'Attach a file or paste a link — a resource needs something to open.');
  }

  const resource = await Resource.create({
    ...updates,
    file,
    uploadedBy: req.user._id,
  });

  const populated = await Resource.findById(resource._id).populate(
    'uploadedBy',
    UPLOADER_FIELDS
  );

  res.status(201).json({
    success: true,
    data: { resource: populated.toPublicJSON({ userId: req.user._id, canManage: true }) },
  });
});

/**
 * PATCH /api/resources/:id
 *
 * Metadata only. Swapping the file out from under people who have already
 * downloaded and cited it would be a different resource wearing the same id —
 * that is a new upload, not an edit.
 */
const updateResource = asyncHandler(async (req, res) => {
  const resource = await Resource.findById(req.params.id).populate(
    'uploadedBy',
    UPLOADER_FIELDS
  );
  if (!resource) throw new ApiError(404, 'Resource not found');
  if (!canManage(resource, req.user)) {
    throw new ApiError(403, 'You can only edit a resource you uploaded.');
  }

  const updates = readBody(req.body);

  // Clearing the link on a link-only resource would leave nothing to open.
  if ('link' in updates && !updates.link && !resource.file) {
    throw new ApiError(400, 'This resource has no file, so it needs to keep its link.');
  }

  Object.assign(resource, updates);
  await resource.save();

  const [decorated] = await withViewerState([resource], req.user);
  res.json({ success: true, data: { resource: decorated } });
});

// DELETE /api/resources/:id
const deleteResource = asyncHandler(async (req, res) => {
  const resource = await Resource.findById(req.params.id);
  if (!resource) throw new ApiError(404, 'Resource not found');
  if (!canManage(resource, req.user)) {
    throw new ApiError(403, 'You can only delete a resource you uploaded.');
  }

  const storedName = resource.file?.storedName;

  await Promise.all([
    SavedResource.deleteMany({ resource: resource._id }),
    resource.deleteOne(),
  ]);

  // After the row is gone: an orphaned file is recoverable, a row pointing at
  // a file that no longer exists is a broken download for everyone.
  unlinkQuietly(storedName);

  res.json({ success: true, message: 'Resource removed' });
});

/**
 * GET /api/resources/:id/download
 *
 * Behind authentication even though browsing is public: this streams a file a
 * student uploaded, and an open endpoint is one crawler away from being a
 * public file host. Always sent as an attachment so nothing renders inline.
 */
const downloadResource = asyncHandler(async (req, res) => {
  const resource = await Resource.findById(req.params.id);
  if (!resource) throw new ApiError(404, 'Resource not found');
  if (!resource.file) {
    throw new ApiError(404, 'This resource is a link, not a file.');
  }

  const full = resolveStoredPath(resource.file.storedName);
  if (!fs.existsSync(full)) {
    throw new ApiError(410, 'That file is no longer on the server.');
  }

  // Counted before the stream so a client that aborts mid-download still
  // registers as interest. Failing to count must not fail the download.
  Resource.updateOne({ _id: resource._id }, { $inc: { downloadCount: 1 } }).catch(() => {});

  // Strip anything that could break out of the header value or suggest a path.
  const safeName = path.basename(resource.file.originalName || 'resource').replace(/["\r\n]/g, '');

  res.setHeader('Content-Type', resource.file.mimeType || 'application/octet-stream');
  res.setHeader('Content-Disposition', `attachment; filename="${safeName}"`);
  res.setHeader('X-Content-Type-Options', 'nosniff');
  fs.createReadStream(full).pipe(res);
});

