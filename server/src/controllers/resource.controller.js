const fs = require('fs');
const path = require('path');

const Resource = require('../models/Resource');
const SavedResource = require('../models/SavedResource');
const Profile = require('../models/Profile');
const ApiError = require('../utils/ApiError');
const asyncHandler = require('../utils/asyncHandler');
const normalizeTags = require('../utils/normalizeTags');
const { RESOURCE_DIR } = require('../middlewares/upload.middleware');
const { getProvider } = require('../ai');
const { ROLES } = require('../utils/constants');

const UPLOADER_FIELDS = 'name role avatarUrl';
const { TYPES } = Resource;

/** Moderators clean up anyone's upload; everyone else only their own. */
const canManage = (resource, user) => {
  if (!user) return false;
  if (user.role === ROLES.MODERATOR || user.role === ROLES.ADMIN) return true;
  const uploaderId = resource.uploadedBy?._id ?? resource.uploadedBy;
  return String(uploaderId) === String(user._id);
};

/** Apply a vote of 1 / -1 / 0, the same shape the forum uses. */
const applyVote = (doc, userId, value) => {
  const id = String(userId);
  const drop = (arr) => arr.filter((x) => String(x) !== id);

  doc.upvotes = drop(doc.upvotes);
  doc.downvotes = drop(doc.downvotes);

  if (value === 1) doc.upvotes.push(userId);
  else if (value === -1) doc.downvotes.push(userId);
  // value === 0 clears the vote, which the two drops above already did.
};

/**
 * Resolve the on-disk path for a stored file.
 *
 * `storedName` is generated by the upload middleware and never user-supplied,
 * so this should always land inside the upload directory — the containment
 * check is here so that a bad row in the database still can't read an
 * arbitrary file off the server.
 */
const resolveStoredPath = (storedName) => {
  const full = path.resolve(RESOURCE_DIR, storedName);
  const root = path.resolve(RESOURCE_DIR);
  if (full !== root && !full.startsWith(root + path.sep)) {
    throw new ApiError(400, 'That file path is not valid.');
  }
  return full;
};

/** Best-effort disk cleanup. A missing file must never block the row delete. */
const unlinkQuietly = (storedName) => {
  if (!storedName) return;
  try {
    fs.unlinkSync(resolveStoredPath(storedName));
  } catch (error) {
    if (error.code !== 'ENOENT') {
      console.warn(`[resources] could not remove ${storedName}: ${error.message}`);
    }
  }
};

/**
 * Decorate a page of resources with the viewer's own state in one query
 * rather than one per resource.
 */
const withViewerState = async (resources, user) => {
  if (!user) return resources.map((r) => r.toPublicJSON());

  const saved = await SavedResource.find({
    user: user._id,
    resource: { $in: resources.map((r) => r._id) },
  })
    .select('resource')
    .lean();

  const savedIds = new Set(saved.map((s) => String(s.resource)));

  return resources.map((r) =>
    r.toPublicJSON({
      userId: user._id,
      saved: savedIds.has(String(r._id)),
      canManage: canManage(r, user),
    })
  );
};

