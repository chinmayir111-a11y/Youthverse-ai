// POST /api/resources/:id/vote
const voteResource = asyncHandler(async (req, res) => {
  const value = Number(req.body.value);
  if (![1, 0, -1].includes(value)) {
    throw new ApiError(400, 'Vote must be 1, 0, or -1.');
  }

  const resource = await Resource.findById(req.params.id).populate(
    'uploadedBy',
    UPLOADER_FIELDS
  );
  if (!resource) throw new ApiError(404, 'Resource not found');

  applyVote(resource, req.user._id, value);
  await resource.save();

  const [decorated] = await withViewerState([resource], req.user);
  res.json({ success: true, data: { resource: decorated } });
});

// POST /api/resources/:id/save
const saveResource = asyncHandler(async (req, res) => {
  const resource = await Resource.findById(req.params.id);
  if (!resource) throw new ApiError(404, 'Resource not found');

  // Upsert so saving twice is idempotent rather than a duplicate-key error.
  await SavedResource.updateOne(
    { user: req.user._id, resource: resource._id },
    { $setOnInsert: { user: req.user._id, resource: resource._id } },
    { upsert: true }
  );

  res.json({ success: true, message: 'Saved' });
});

// DELETE /api/resources/:id/save
const unsaveResource = asyncHandler(async (req, res) => {
  await SavedResource.deleteOne({ user: req.user._id, resource: req.params.id });
  res.json({ success: true, message: 'Removed from saved' });
});

