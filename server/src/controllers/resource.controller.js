// POST /api/resources/recommend
const recommendResources = asyncHandler(async (req, res) => {
  const library = await Resource.find().sort({ createdAt: -1 }).limit(40);

  // Never ask the model to shortlist from nothing; it would invent resources.
  if (library.length === 0) {
    return res.json({
      success: true,
      data: { picks: [], noteToStudent: 'The library is empty — add the first resource.' },
    });
  }

  const profile = await Profile.findOne({ user: req.user._id });
  const profileText = [
    `Name: ${req.user.name}`,
    profile?.fieldOfStudy && `Field of study: ${profile.fieldOfStudy}`,
    profile?.educationLevel && `Education level: ${profile.educationLevel}`,
    profile?.skills?.length && `Skills: ${profile.skills.join(', ')}`,
    profile?.interests?.length && `Interests: ${profile.interests.join(', ')}`,
    profile?.goals?.length && `Goals: ${profile.goals.join(', ')}`,
  ]
    .filter(Boolean)
    .join('\n');

  const goal = typeof req.body.goal === 'string' ? req.body.goal.trim().slice(0, 300) : '';

  const result = await getProvider().recommendResources({
    profileText: profileText || '(This student has not filled in their profile.)',
    goal,
    resources: library.map((r) => r.toPublicJSON()),
  });

  const byId = new Map(library.map((r) => [String(r._id), r]));
  const chosen = (result.picks ?? []).filter((p) => byId.has(String(p.resourceId)));
  const decorated = await withViewerState(
    chosen.map((p) => byId.get(String(p.resourceId))),
    req.user
  );

  res.json({
    success: true,
    data: {
      picks: chosen.map((pick, i) => ({ ...pick, resource: decorated[i] })),
      noteToStudent: result.noteToStudent,
    },
  });
});

