// GET /api/resources
const listResources = asyncHandler(async (req, res) => {
  const query = {};

  if (req.query.type) {
    if (!TYPES.includes(req.query.type)) {
      throw new ApiError(400, `Unknown type "${req.query.type}"`);
    }
    query.type = req.query.type;
  }

  const exact = (value) =>
    new RegExp(`^${String(value).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`, 'i');

  if (req.query.subject) query.subject = exact(req.query.subject);
  if (req.query.tag) query.tags = exact(req.query.tag);
  if (req.query.hasFile === 'true') query.file = { $ne: null };

  const q = typeof req.query.q === 'string' ? req.query.q.trim() : '';
  if (q) query.$text = { $search: q };

  const resources = await Resource.find(query)
    .populate('uploadedBy', UPLOADER_FIELDS)
    .sort({ createdAt: -1 })
    .limit(100)
    .collation({ locale: 'en' });

  // Sorting by score has to happen after the query: it is derived from two
  // arrays rather than stored, so Mongo has nothing to sort on.
  const ordered =
    req.query.sort === 'helpful'
      ? [...resources].sort((a, b) => b.score() - a.score())
      : resources;

  res.json({ success: true, data: { resources: await withViewerState(ordered, req.user) } });
});

// GET /api/resources/meta  — the filter bar's contents
const getMeta = asyncHandler(async (req, res) => {
  const [byType, facetDocs, withFiles] = await Promise.all([
    Resource.aggregate([{ $group: { _id: '$type', count: { $sum: 1 } } }]),
    Resource.find().select('subject tags').lean(),
    Resource.countDocuments({ file: { $ne: null } }),
  ]);

  const counts = Object.fromEntries(TYPES.map((t) => [t, 0]));
  for (const row of byType) counts[row._id] = row.count;

  res.json({
    success: true,
    data: {
      types: TYPES,
      counts,
      subjects: [...new Set(facetDocs.map((d) => d.subject).filter(Boolean))].sort().slice(0, 60),
      tags: [...new Set(facetDocs.flatMap((d) => d.tags))].sort().slice(0, 60),
      withFiles,
    },
  });
});

// GET /api/resources/me/saved
const listSaved = asyncHandler(async (req, res) => {
  const saved = await SavedResource.find({ user: req.user._id })
    .sort({ createdAt: -1 })
    .populate({ path: 'resource', populate: { path: 'uploadedBy', select: UPLOADER_FIELDS } });

  // A bookmark can outlive its resource if it was deleted mid-session.
  const resources = saved.map((s) => s.resource).filter(Boolean);

  res.json({ success: true, data: { resources: await withViewerState(resources, req.user) } });
});

// GET /api/resources/me  — what the viewer has contributed
const listMine = asyncHandler(async (req, res) => {
  const resources = await Resource.find({ uploadedBy: req.user._id })
    .populate('uploadedBy', UPLOADER_FIELDS)
    .sort({ createdAt: -1 });

  res.json({ success: true, data: { resources: await withViewerState(resources, req.user) } });
});

// GET /api/resources/:id
const getResource = asyncHandler(async (req, res) => {
  const resource = await Resource.findById(req.params.id).populate(
    'uploadedBy',
    UPLOADER_FIELDS
  );
  if (!resource) throw new ApiError(404, 'Resource not found');

  const [decorated] = await withViewerState([resource], req.user);
  res.json({ success: true, data: { resource: decorated } });
});

